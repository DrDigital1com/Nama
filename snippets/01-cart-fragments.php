<?php
/**
 * מבטל את wc-cart-fragments בעמודים שאינם עמודי חנות.
 *
 * הרקע: ווקומרס טוענת סקריפט שמבצע קריאת AJAX בכל טעינת עמוד באתר,
 * רק כדי לעדכן את מונה העגלה. בעמודי תוכן ובדף הבית זו בקשה מיותרת
 * שמתווספת לכל צפייה.
 *
 * ⚠️  אזהרה — לקרוא לפני ההפעלה:
 * תבנית Woodmart מציגה מונה עגלה בכותרת של כל עמוד. אם המונה מפסיק
 * להתעדכן אחרי הוספה לעגלה מדף הבית או מעמוד תוכן — לכבות את הקטע הזה.
 * זו הסיבה שהוא לא מופעל כברירת מחדל.
 *
 * בדיקה אחרי הפעלה:
 *   1. להוסיף מוצר לעגלה מעמוד מוצר  -> המונה מתעדכן?
 *   2. לעבור לדף הבית                -> המונה עדיין מציג את הכמות הנכונה?
 *   3. להיכנס לעגלה                  -> המוצר שם?
 * אם אחד מהשלושה נכשל — לכבות.
 *
 * התקנה: WPCode -> Add Snippet -> PHP Snippet -> Save & Activate
 */

add_action(
	'wp_enqueue_scripts',
	function () {
		if ( ! function_exists( 'is_woocommerce' ) ) {
			return;
		}
		// בעמודי חנות, עגלה, תשלום וחשבון — להשאיר כפי שהוא.
		if ( is_woocommerce() || is_cart() || is_checkout() || is_account_page() ) {
			return;
		}
		wp_dequeue_script( 'wc-cart-fragments' );
	},
	99
);
